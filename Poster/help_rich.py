def build_help_rich_message() -> InputRichMessage:
    """
    Собирает справку Poster способом `blocks` (§48).

    Структура: заголовок, введение, подсказка о свёрнутых разделах,
    разделитель и ровно десять свёрнутых `InputRichBlockDetails` (§52).
    Функция вызывается на каждое открытие справки и собирает новую
    структуру: изменяемых общих объектов нет.
    """
    blocks: list[RichBlock] = [
        # 1 — самый крупный заголовок официальной схемы Bot API.
        InputRichBlockSectionHeading(text=tr("help.rich.title"), size=1),
        InputRichBlockParagraph(text=tr("help.rich.intro")),
        InputRichBlockParagraph(text=tr("help.rich.hint")),
        InputRichBlockDivider(),
    ]
    for title_key, paragraph, items in _SECTIONS:
        blocks.append(
            InputRichBlockDetails(
                summary=tr(title_key),
                # §52: при первом открытии видны заголовок, описание и
                # перечень свёрнутых блоков; раскрытие ничего не отправляет.
                # is_open не передаётся: отсутствие поля = свёрнуто.
                blocks=(
                    InputRichBlockParagraph(text=_fill(paragraph)),
                    InputRichBlockList(
                        items=tuple(
                            InputRichBlockListItem(
                                blocks=(InputRichBlockParagraph(text=_fill(item)),)
                            )
                            for item in items
                        )
                    ),
                ),
            )
        )
    return InputRichMessage(blocks=tuple(blocks))


def help_section_titles() -> tuple[str, ...]:
    """Названия десяти разделов (в порядке справки). Для проверок и тестов."""
    return tuple(tr(title_key) for title_key, _paragraph, _items in _SECTIONS)
