# Подписи с переменными каталога: в справке показывается общая форма
# («🖼 Фото (n)» — число фото у каждого анонса своё).
_LABEL_VARS: dict[str, dict[str, object]] = {
    "finished_photos": {"count": "n"},
}


def _label(token: str) -> str:
    """Подпись кнопки из каталога по токену текста раздела."""
    return tr(_LABELS[token], **_LABEL_VARS.get(token, {}))


def _fill(template: str) -> str:
    """
    Подставляет в текст раздела подписи кнопок из каталога.

    Токены — ключи `_LABELS`; других фигурных скобок в текстах разделов нет
    (проверяется тестом структуры справки).
    """
    return template.format(**{token: _label(token) for token in _LABELS})


