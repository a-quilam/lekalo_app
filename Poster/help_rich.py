"""
Содержание справки Poster как Rich Message (Poster 2.5, этап E, §51–52).

Справка — единственное место, где используется Rich Message (§46). Здесь
только СТРУКТУРА и тексты разделов: отправка живёт в `rich_message.py`,
навигация — в `handlers/main_menu.py`.

Почему содержание разбито так:

- короткие строки, которые владелец захочет поправить формулировкой —
  заголовок, введение, подсказка о свёрнутых разделах и НАЗВАНИЯ десяти
  разделов — берутся из каталога `config/ui_texts.yaml` (ключи `help.rich.*`);
- упоминания кнопок в текстах разделов подставляются из каталога ТЕМИ ЖЕ
  ключами, что и сами кнопки (`_LABELS`): если владелец переименует кнопку,
  справка не начнёт называть её по-старому (MINOR-2 приёмки E);
- подробные тексты разделов остаются константами этого модуля: Rich-контент
  структурирован (списки, абзацы, свёрнутые блоки), каталог плоских строк
  для него не подходит, а сотня ключей `help.rich.sectionN.itemM` сделала бы
  каталог нередактируемым. Это осознанное решение, зафиксировано в отчёте.

Структура (§52): главный заголовок, введение, короткая подсказка, затем
десять СВЁРНУТЫХ раскрываемых разделов (поле `is_open` не передаётся —
по официальной схеме отсутствие поля и означает «свёрнуто»): при первом
открытии видно только название и перечень тем, раскрытие не отправляет
новое сообщение.

Все тексты статические: никакой генерации во время запроса (§50).
"""

